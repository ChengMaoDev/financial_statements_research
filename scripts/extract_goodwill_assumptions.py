def pdf_text(filename: str, cache: dict[str, str]) -> str:
    if filename not in cache:
        result = subprocess.run(
            ["pdftotext", "-layout", str(PDF_DIR / filename), "-"],
            capture_output=True,
            text=True,
            timeout=300,
            check=False,
        )
        cache[filename] = result.stdout
    return cache[filename]


def compact(text: str) -> str:
    return re.sub(r"\s+", "", text)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--all", action="store_true", default=True, help="默认执行全部；保留该开关用于兼容旧命令"
    )
    args = parser.parse_args()
    if not args.all:  # 默认 True；仅显式 --no-all 时才打印帮助
        parser.print_help()
        return 1

    cache: dict[str, str] = {}
    problems: list[str] = []
    for company, value, filename in ANCHORS:
        if compact(value) not in compact(pdf_text(filename, cache)):
            problems.append(f"{company} 的「{value}」未出现在 {filename}")

    with OUT.open("w", encoding="utf-8-sig", newline="") as stream:
        writer = csv.writer(stream, lineterminator="\n")
        writer.writerow(["公司", "资产组", "参数项", "2025", "2024", "出处", "数据性质"])
        for company, group, item, current, previous, source in ROWS:
            writer.writerow([company, group, item, current, previous, source, "披露值"])

    print(f"{'公司':<8}{'资产组':<18}{'参数项':<20}{'2025':>20}{'2024':>20}")
    print("-" * 88)
    for company, group, item, current, previous, _ in ROWS:
        print(f"{company:<8}{group:<18}{item:<20}{current:>20}{previous:>20}")

    print(f"\n写入 {OUT.relative_to(ROOT)}: {len(ROWS)} 行")
    for problem in problems:
        print(f"校验失败：{problem}", file=sys.stderr)
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
