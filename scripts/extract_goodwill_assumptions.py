"""商誉减值测试假设：可收回金额靠什么参数算出来的。

为什么重要：
商誉是「过去买贵了的部分」，减值测试的假设直接决定它要不要减。三家的关键参数
差异很大，而且格力是唯一在计提的：

| 公司 | 商誉账面 | 资产组 | 税前折现率 | 永续增长率 | 2025 减值 |
|---|---|---|---|---|---|
| 美的 | 342.57 亿 | KUKA 234.35 / TLSC 20.86 / 小天鹅 13.61 | 10.08%–16.25% | 1.00%–2.00% | 0 |
| 海尔 | 273.00 亿 | GEA 208.83 / CCR 23.29 / Candy 21.30 | 10.67%–15.55% | 1.70%–2.00% | 0 |
| 格力 | 13.24 亿 | 盾安 11.98（其余已全额减值） | 12.72% | 0.00% | 0.44 亿 |

四个观察：

1. **格力对盾安用了 0% 的永续增长率**，美的 KUKA 用 2.00%、小天鹅 2.00%、
   海尔用 1.7%–2.0%。永续增长率每降 1 个百分点，可收回金额普遍下降 10%–15%。
   格力最保守，同时它也是唯一还在计提商誉减值的。
2. **格力的盾安资产组可收回金额是账面价值的 2.16 倍**（128.14 亿 vs 59.36 亿），
   安全垫极厚；美的/海尔不披露可收回金额，只披露参数。
3. **美的 KUKA 的毛利率假设连续两年下调**（22.68%–23.65% → 19.61%–22.93%），
   同时折现率从 10.88% 降到 10.08%——一个变差、一个变好，方向相反。
4. **格力钛 2025 年没有新增商誉减值**（2024 年计提 2.54 亿，2025 年 0），因为
   6.13 亿商誉已在以前年度全额减值完毕，账面价值为 0。

三个陷阱：

1. **美的按千元、海尔/格力按元**，且本表全部是「比率」和「金额」混排，
   金额要单独标注单位来源。
2. **海尔的参数是区间，不是单点**：永续增长率 1.7%–2.0%、复合收入增长率
   2.61%–9.83%、EBITDA 盈利率 1.98%–14.50%、税前折现率 10.67%–15.55%。
   取中值会丢失关键信息，必须原样记录区间。
3. **格力的盾安资产组拆成 4 个子资产组**（制冷配件、设备、热工、热管理），
   每个子资产组的收入增长率假设从 7.98% 到 31.40% 不等，只有一个统一的
   12.72% 折现率。不能把最高增长率当成整个盾安的增长率。

用法：
    uv run python3 scripts/extract_goodwill_assumptions.py --all
"""

