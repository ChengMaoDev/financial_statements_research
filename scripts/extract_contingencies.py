def flatten(text: str) -> str:
    """去空白，避免原文换行把「5.47 亿巴西雷亚尔」拆成两段导致匹配失败。"""
    return re.sub(r"\s+", "", text)


def report_text(name: str) -> str:
    return pdf_text(PDF_DIR / name)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--all", action="store_true")
    args = parser.parse_args()
    if not args.all:
        parser.print_help()
        return 0

    problems: list[str] = []

    # 1) 断言每个数字/关键词确实在对应年报里
    cache: dict[str, str] = {}
    for name, fragment, _ in ANCHORS:
        if name not in cache:
            cache[name] = report_text(name)
        if flatten(fragment) not in flatten(cache[name]):
            problems.append(f"断言失败：「{fragment}」未出现在 {name}")
    print(
        f"[断言] {len(ANCHORS)} 条原文片段，"
        f"通过 {len(ANCHORS) - sum(1 for q in problems if q.startswith('断言失败'))} 条"
    )

    # 1b) 来源引用里带原文数字的（如「160,494.40 万元」），逐个回年报核对。
    #     四舍五入到亿元后相同不代表引用抄对了——实测曾把格力的 223,150.20
    #     万元误抄成 223,229.28 万元，两者折成都 22.32 亿，靠金额查不出来。
    checked_citations = 0
    stem_of = {"美的集团": "美的", "海尔智家": "海尔", "格力电器": "格力"}
    for company, year, _category, item, _amount, _nature, source in ROWS:
        name = f"{stem_of[company]}{year}.pdf"
        # 来源里若另写了「NNNN 年报」，以它为准：2024 年行的可比数其实印在
        # 2025 年报里（如美的资本承诺 11,346,127 千元）。
        cited = re.search(r"(\d{4}) 年报", source)
        name = f"{stem_of[company]}{cited.group(1)}.pdf" if cited else name
        if "分红送配" in source:  # 引用本仓库另一张表，回查那张表
            name = "分红送配.csv"
        # 只查数字、不连带单位：美的的单位写在表头「金额单位为人民币千元」，
        # 表体数字后不跟「千元」，连排匹配会全部落空。
        for token in re.findall(r"\d{1,3}(?:,\d{3})+(?:\.\d+)?", source):
            if name not in cache:
                cache[name] = (
                    (FIN / name).read_text(encoding="utf-8", errors="ignore")
                    if name.endswith(".csv")
                    else report_text(name)
                )
            checked_citations += 1
            # 来源同时引了年报与另一张表时（如「8,248,280,749.27 出自年报、
            # 8.9151 出自 分红送配.csv」），允许数字落在任一处；抄错的数两处都不会有。
            haystacks = [cache[name]]
            if name.endswith(".csv"):
                report = f"{stem_of[company]}{year}.pdf"
                if report not in cache:
                    cache[report] = report_text(report)
                haystacks.append(cache[report])
            if all(flatten(token) not in flatten(h) for h in haystacks):
                problems.append(
                    f"来源引用核对失败：{company} {year}「{item}」的 {token} 不在 {name}"
                )
    # 来源里出现「见/取自 X.csv」的交叉引用，也去那张表核一下数字在不在
    cross = 0
    for _company, _year, _c, item, _amount, _n, source in ROWS:
        ref = re.search(r"(\S+\.csv)", source)
        if not ref:
            continue
        path = FIN / ref.group(1)
        if not path.exists():
            problems.append(f"交叉引用失败：{item} 指向不存在的 {ref.group(1)}")
            continue
        body = path.read_text(encoding="utf-8-sig")
        cross += 1
        # 交叉引用的是「输入数字」（如派息比例 8.9151），不是本行算出的结果
        # （92.52 亿股是反推值，那张表里本来就没有）。所以核来源里的数字。
        stripped = re.sub(r"\d{1,3}(?:,\d{3})+(?:\.\d+)?", " ", source)
        tokens = re.findall(r"\d+\.\d{2,}|\d{4}-\d{2}-\d{2}", stripped)
        missing = [t for t in tokens if t not in body]
        if tokens and missing:
            problems.append(f"交叉引用核对失败：{item} 引用的 {missing} 不在 {ref.group(1)}")
    print(f"[来源核对] 回查 {checked_citations} 处原文数字 + {cross} 处跨表引用")

    # 1c) 海尔：只复算「合计 ÷ 每股 = 隐含基数」这一条。
    #     年报说「本次 + 2025 年度中期已实施 = 归母的 55.0%」，但**中期金额未在
    #     这份年报里单独披露**，反推出的中期数再拿去验证 55.0% 属于循环论证，不做。
    haier_total = 8_248_280_749.27
    implied_shares = haier_total / (8.867 / 10)
    print(
        f"[勾稽] 海尔 隐含可分配基数：{haier_total:,.2f} ÷ (8.867/10) = "
        f"{implied_shares:,.0f} 股（{implied_shares / 1e8:.2f} 亿股，年报未直接给）"
    )
    print("       中期金额未在本年报单独披露，55.0% 的占比无法独立复算，不反推")

    # 2) 期后分红勾稽
    for company, per_ten, shares, stated in DIVIDEND_CHECKS:
        recomputed = per_ten / 10 * shares
        gap = recomputed - stated
        ok = abs(gap) <= 1
        print(
            f"[勾稽] {company} 期后分红：{per_ten}/10 × {shares:,} = "
            f"{recomputed:,.0f}（披露 {stated:,}）  {'OK' if ok else f'差 {gap:,.0f}'}"
        )
        if not ok:
            problems.append(f"{company} 期后分红复算不平，差 {gap:,.0f} 元")

    # 3) 美的巴西纠纷：缺口 = 潜在损失 − 承诺赔付
    values = {(r[0], r[1], r[3]): r[4] for r in ROWS}
    for year, loss, cover in (("2025", 6.99, 1.68), ("2024", 6.61, 1.52)):
        stated = values.get(("美的集团", year, "赔付承诺未覆盖的风险缺口"))
        recomputed = round(loss - cover, 2)
        ok = stated is not None and abs(recomputed - float(stated)) <= 0.01
        print(
            f"[勾稽] 美的 {year} 巴西纠纷缺口：{loss} − {cover} = {recomputed}"
            f"（表内 {stated}）  {'OK' if ok else '差异'}"
        )
        if not ok:
            problems.append(f"美的 {year} 或有事项缺口勾稽不平")

    # 4) 美的 2025 资本承诺合计 = 分项相加
    parts = values.get(("美的集团", "2025", "资本性支出—房屋建筑物及机器设备"))
    invest = values.get(("美的集团", "2025", "投资承诺"))
    total = values.get(("美的集团", "2025", "资本性支出承诺合计"))
    if None not in (parts, invest, total):
        recomputed = round(float(parts) + float(invest), 2)
        ok = abs(recomputed - float(total)) <= 0.01
        print(
            f"[勾稽] 美的 2025 资本承诺：{parts} + {invest} = {recomputed}"
            f"（披露合计 {total}）  {'OK' if ok else '差异'}"
        )
        if not ok:
            problems.append("美的 2025 资本承诺合计与分项不符")

    with OUT.open("w", encoding="utf-8-sig", newline="") as stream:
        writer = csv.writer(stream, lineterminator="\n")
        writer.writerow(["公司", "年度", "类别", "项目", "金额(亿元)", "数据性质", "来源"])
        writer.writerows(ROWS)

    print(f"\n{'公司':<8}{'年度':<6}{'类别':<8}{'项目':<34}{'金额':>9}  性质")
    print("-" * 78)
    for row in ROWS:
        print(f"{row[0]:<8}{row[1]:<6}{row[2]:<8}{row[3][:32]:<34}{row[4]:>9}  {row[5]}")

    tail = OUT.relative_to(ROOT)
    print(f"\n写入 {tail}: {len(ROWS)} 行")
    for problem in problems:
        print(f"注意：{problem}", file=sys.stderr)
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
