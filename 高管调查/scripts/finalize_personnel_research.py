def write_csv(name, rows):
    if not rows:
        return
    with (OUT / name).open("w", encoding="utf-8-sig", newline="") as stream:
        writer = csv.DictWriter(stream, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)


def parse_rows(text, columns):
    result = []
    for line in text.strip().splitlines():
        fields = line.strip().split("|")
        if len(fields) != len(columns):
            raise ValueError(f"Incorrect note fields: {line}")
        result.append(dict(zip(columns, fields)))
    return result


def source_catalog():
    config = json.loads((OUT / "research_sources.json").read_text(encoding="utf-8"))
    with (ROOT / "H股披露" / "来源清单.csv").open(encoding="utf-8-sig", newline="") as stream:
        filings = {row["document_id"]: row for row in csv.DictReader(stream)}
    sources = {}
    for key, document_id in config["annual_documents"].items():
        row = filings[document_id]
        sources[key] = {
            "id": key, "company": row["公司"], "title": row["原始标题"],
            "publisher": "发行人／官方披露渠道", "date": row["披露日期"],
            "url": row["PDF下载URL"], "path": row["仓库路径"],
            "status": "复用已归档全文；本轮阅读相应人物与控制章节",
        }
    for row in config["additional_sources"]:
        sources[row["id"]] = row.copy()
    for row in sources.values():
        row["retrieved"] = config["retrieval_date"]
        if row.get("path"):
            path = ROOT / row["path"]
            with path.open("rb") as stream:
                row["sha256"] = hashlib.file_digest(stream, "sha256").hexdigest()
            row["bytes"] = path.stat().st_size
            info = subprocess.run(["pdfinfo", str(path)], capture_output=True,
                                  encoding="utf-8", errors="replace", check=True)
            match = re.search(r"^Pages:\s*(\d+)", info.stdout, re.M)
            row["pages"] = int(match.group(1)) if match else None
    return sources


TOKEN = re.compile(r"〔([A-Z][A-Z0-9-]*)(?::(\d+(?:-\d+)?))?〕")
LINK = re.compile(r"\[([A-Z][A-Z0-9-]*)(?:，PDF第(\d+(?:—\d+)?)页)?\]\(([^)]+)\)")


def citation(source, page):
    url = source["url"]
    if page:
        first = int(page.split("-")[0])
        last = int(page.split("-")[-1])
        if first < 1 or last < first or (source.get("pages") and last > source["pages"]):
            raise ValueError(f"Invalid original PDF page: {source['id']} {page}")
        label = source["id"] + "，PDF第" + page.replace("-", "—") + "页"
        url = url.split("#")[0] + "#page=" + str(first)
    else:
        label = source["id"]
    return f"[{label}]({url})"


def finalize_report(company, name, sources, people):
    path = ROOT / name
    text = path.read_text(encoding="utf-8")
    used = []
    for match in TOKEN.finditer(text):
        key = match.group(1)
        if key not in sources:
            raise KeyError(f"Unknown source: {key}")
        if key not in used:
            used.append(key)
    for match in LINK.finditer(text):
        if match.group(1) not in used:
            used.append(match.group(1))
    text = TOKEN.sub(lambda m: citation(sources[m.group(1)], m.group(2)), text)
    lines = ["<!-- RESEARCH_SOURCE_INDEX_START -->", "", "| 编号 | 来源及日期 | 原件/获取状态 |", "| --- | --- | --- |"]
    for key in used:
        row = sources[key]
        local = f"[仓库原件]({row['path']})；" if row.get("path") else ""
        lines.append(f"| {key} | [{row['title']}]({row['url']})；{row['publisher']}；{row['date']} | {local}{row['status']} |")
    lines += ["", "<!-- RESEARCH_SOURCE_INDEX_END -->"]
    index = "\n".join(lines)
    if "〔SOURCE_INDEX〕" in text:
        text = text.replace("〔SOURCE_INDEX〕", index)
    else:
        text = re.sub(r"<!-- RESEARCH_SOURCE_INDEX_START -->.*?<!-- RESEARCH_SOURCE_INDEX_END -->", index, text, flags=re.S)
    if re.search(r"〔(?:[A-Z]|SOURCE_INDEX)", text):
        raise ValueError(f"Unresolved report reference in {name}")
    path.write_text(text, encoding="utf-8")
    evidence = []
    heading = ""
    names = [p["姓名"] for p in people if p["公司"] == company]
    for number, line in enumerate(text.split("<!-- RESEARCH_SOURCE_INDEX_START -->")[0].splitlines(), 1):
        if line.startswith("#"):
            heading = line.lstrip("# ")
        refs = list(LINK.finditer(line))
        if not refs:
            continue
        clean = LINK.sub(lambda m: m.group(1), line)
        related = [person for person in names if person in heading or person in clean]
        for match in refs:
            key = match.group(1)
            source = sources[key]
            evidence.append({
                "证据ID": f"E-{PREFIX[company]}-{len(evidence)+1:04d}", "公司": company,
                "关联人物": ";".join(related), "报告": name, "报告行": number,
                "主题章节": heading, "正文摘录": clean[:700],
                "记录性质": "正文证据关联；事实、来源说法与分析以正文标示为准",
                "来源ID": key, "文档标题": source["title"], "发布机构": source["publisher"],
                "发布日期": source["date"], "事件日期": "见正文时间线或career_timeline.csv",
                "PDF文件页序": (match.group(2) or "").replace("—", "-"),
                "印刷页码": "未在统一台账换算；以原件页脚为准",
                "网页栏目或定位": heading if not match.group(2) else "",
                "URL": match.group(3), "仓库原件": source.get("path", ""),
                "检索日": source["retrieved"], "来源状态与限制": source["status"],
            })
    return evidence


